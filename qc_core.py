    q.score_imm(m)[1]       # 代入感，0–10，越高越好
    q.score_rhy(m)[1]       # 节奏，0–10，越高越好
    q.score_syn(m)[1]       # 句法，0–10，越高越好
    q.score_total({...})    # 总分，0–10，越高越好
    q.compliance(body, title)   # 合规硬规则，返回违规项列表

