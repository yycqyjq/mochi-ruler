def clamp(x, lo=0.0, hi=10.0):
    return max(lo, min(hi, x))


def _wavg(s, w):
    """逐项分的加权平均，先按权重和归一化。

    权重表只表达相对重要性，不必凑成 1.0；删掉指标时也不用重新配平。
    输入是 0–10 的逐项分，输出必然落在 0–10。

    逐项分为 None 的项**直接跳过、权重不参与归一**（2026-09-14）：None 表示
    「该项在本章不适用」（如无对话的章的 dial_sent）。按 0 计入等于把它当成
    「写得最差」扣分，按满分计入又是虚高——跳过才是中性。
    """
    ks = [k for k in w if s.get(k) is not None]
    tot = sum(w[k] for k in ks)
    return clamp(sum(s[k] * w[k] for k in ks) / tot) if tot else 0.0


def good(v, target, over):
    """把单指标原始值折算成 0–10 分，越高越好。

    target = 达标值 → 10 分；over = 超标值 → 0 分；中间线性取值。
    target 可以大于也可以小于 over（两种方向都行），公式自带方向，
    因此不需要任何额外的「越低越好 / 越高越好」方向表。
    旧版「AI 味」用的正是它的补数 10 − good(v)，两者数值严格互补。

    v 为 None（该项在本章不适用）时返回 None，交给 _wavg() 跳过。
    """
    if v is None:
        return None
    if over == target:
        return 0.0
    return clamp((over - v) / (over - target) * 10)


# 逐项评分规范：(达标值, 超标值)。由各维度阈值表合并而来。
ITEM_TARGET = {}
for _tbl in (GOOD_BAD, IMM_GOOD_BAD, HUMAN_GOOD_BAD,
             RHY_GOOD_BAD, SYN_GOOD_BAD):
    ITEM_TARGET.update(_tbl)
ITEM_TARGET["cv"] = CV_RANGE
# 退出打分的项（`ttr` / `net_short` / `enum` / `imm_cog` / `imm_perc` /
# `imm_soma`）不在这张表里，故 item_score() 对它们返回 None、前端显示「—」；
# 它们的原始值仍由 metrics() 照常算出备查。
# `act` 2026-09-14 已从「退出」名单移出，回到 IMM_GOOD_BAD 参与打分。

def item_score(k, v):
    """单个指标的逐项分，0–10，越高越好。

    没有阈值规范、或取值为 None 时返回 None（前端显示为 —）。
    原「区间型」机制（落在区间内满分）已随代入感重定标删除：那两个指标
    （imm_perc / imm_soma）当时改用与其余各维一致的单点阈值——但同日又因
    真人侧左尾过重而整体退出打分，见 IMM_GOOD_BAD 上方记录。
    """
    if v is None:
        return None
    t = ITEM_TARGET.get(k)
    if t is None:
        return None
    return good(v, t[0], t[1])


def strip_meta(t):
    t = re.sub(r"^#.*$", "", t, flags=re.M)
    t = re.sub(r"^>.*$", "", t, flags=re.M)
    return t


def split_chapters(text):
    """按常见中文网文格式拆章，支持 Markdown / 中文章号 / 数字序号 / Chapter /
    纯数字前缀（如「01开篇」「02 别离」）/「第X集 卷名 第X章」两级章头。

    「纯数字前缀」这一类（数字紧跟标题、中间没有「第…章」也没有顿号）在导出
    的网文 txt 里很常见，但它没有任何显式分隔符，误伤风险高，所以加了四重
    护栏：① 该行前面必须是空行；② 数字 1–4 位；③ 数字后紧跟汉字；④ 整行
    ≤24 字，且数字后不能是「年/月/日…」这类时间单位。实测在长篇网文与
    AI 语料上，只有原本就拆不开的那一本被修正，其余文件拆章结果逐字不变。

    两级章头按「集+章同行」匹配，作为普通章头的备选分支并进同一个模式，
    而不是独立模式：混合格式文件（前几卷普通章号、后几卷按卷重编号）两种
    章头必须同时生效，单选任何一种都会在另一半留出巨块。卷名部分用非贪婪
    懒匹配，天然限制在同一行内。"""
    pats = [
        r"\n(?=#\s+(?:第[一二三四五六七八九十百千\d]{1,6}[章节]|楔子|序章|番外))",
        # 分支一：两级章头「第X集/卷/部 卷名 第Y章 章名」（按卷重编号的导出
        # 格式很常见，如「第四集 第十七章 幽深地穴」）；分支二：普通「第X章」。
        # 同一行里两支互不误伤：普通章头行不以「第X集」开头，两级章头行的
        # 「第X集」后面不是「章/节」，各自只可能命中一支。
        r"\n(?=\s*(?:第[一二三四五六七八九十百千\d]{1,6}[集卷部]\s.*?"
        r"第[一二三四五六七八九十百千\d]{1,6}章|"
        r"第[一二三四五六七八九十百千\d]{1,6}[章节])(?:\s|$))",
        # 分支三（2026-09-16 新增）：「第X章：标题」——章号后紧跟全角/半角冒号、
        # 无空格。实测某完整本用此格式（804 章），旧 pattern 只认 `(?:\s|$)` 会把
        # 整本并成 1 段（205 万字）。**必须要求顶格**（`\n` 后直接是「第X章」，
        # 不允许 `\u3000` 段首缩进）——否则会误切正文里缩进的引用（实测两本已登记
        # 基准各含 1–3 处「\u3000\u3000第X章：」引用，放宽缩进会漂移 57 键）。
        r"\n(?=第[一二三四五六七八九十百千\d]{1,6}[章节][：:])",
        r"\n(?=\s*(?:Chapter|CHAPTER)\s*\d+\b)",
        r"\n(?=\s*(?:楔子|序章|番外)(?:\s|$))",
        r"\n(?=\s*\d{1,4}[、.．]\s*\S)",
        r"\n[ \t\u3000\r]*\n(?=[ \t\u3000\r]*\d{1,4}[ \t\u3000\r]?"
        r"(?!年|月|日|时|分|秒|点|号|届|周年|℃|%)[\u4e00-\u9fa5][^\n]{0,22}\n)",
    ]
    # 2026-09-14 修复：选型判据由「切段数最多」改为「有效段最多」（strip_meta
    # 后 ≥300 字，与下方过滤同口径）。旧判据会被正文里嵌的「数字. 数字」式
    # 索引/目录列表带偏：某 990 万字文件嵌了 5687 行「1. 63」式目录，数字顿点
    # 模式靠段数险胜「第X章」模式，整本书被目录行切碎成 5688 段、过滤后只剩
    # 38 块垃圾章。目录碎段几乎全 <300 字，按有效段计数永远赢不了；而真正
    # 该用某模式的文件，其有效段数也必然最多，选型结果不变。
    def _valid(parts):
        return [p for p in parts
                if len(re.sub(r"\s", "", strip_meta(p))) >= 300]

    best = None
    for p in pats:
        parts = re.split(p, text)
        n = len(_valid(parts))
        if best is None or n > best[0]:
            best = (n, parts)
    parts = best[1]
    out = []
    for p in parts:
        title = p.split("\n")[0].strip()
        body = strip_meta(p)
        if len(re.sub(r"\s", "", body)) < 300:
            continue
        out.append((title, body))
    return out


def sentences(body):
    b = re.sub(r"[*>#]", "", body)
    return [re.sub(r"\s", "", s)
            for s in re.split(r"[。！？…]+", b) if len(re.sub(r"\s", "", s)) >= 2]


def paras(body):
    """正文段落。排除 Markdown 分隔线（---/***/===），否则章尾会被
    分隔线占据，导致钩子、段长、短段率等全部算错。"""
    out = []
    for l in body.split("\n"):
        s = l.strip()
        if not s or len(re.sub(r"\s", "", s)) < 2:
            continue
        if re.fullmatch(r"[-=*\u2014\u2013_]{2,}", s):
            continue
        out.append(s)
    return out


def is_dialogue(p):
    return bool(QUOTE.search(p))


# ---------------------------------------------------------------- 指标

def tail_gold_hits(body):
    hits = []
    for p in paras(body):
        if is_dialogue(p):
            continue
        seg = [x for x in re.split(r"[。！？…]", p) if x.strip()]
        if not seg:
            continue
        s = re.sub(r"\s", "", seg[-1])
        if 5 <= len(s) <= 20 and not re.search(r"[了吗呢吧啊哦哟]", s) \
                and re.search(r"是|在|有|得|成|叫", s):
            hits.append(s)
    return hits


def imm_stats(body):
    k = max(len(re.sub(r"\s", "", body)), 1) / 1000.0
    return {
        "imm_perc": len(PERC.findall(body)) / k,
        "imm_cog": len(COG.findall(body)) / k,
        "imm_soma": len(SOMA.findall(body)) / k,
    }


def net_stats(body):
    ps = paras(body)
    ss = sentences(body)
    # dial_sent：引号内句均字数（字）。只统计成对引号内的文字：所有引号
    # 字符（弯/直/直角）按奇偶配对（偶位开、奇位闭），引号不成对的段落
    # 整段作废（宁缺勿错）。
    # 2026-09-14 由 net_dial（含引号段落占比）换口径而来。原口径三重混淆：
    # 段级粒度粗、被句长绑架、且「对话量」本身人机零区分（引号字占比
    # 真人/AI sep 0.07）。新口径测「对话的写法」：AI 的对话是短促的戏剧腔
    # 单句，真人对话句更长更松。sep 0.89 / 残差 0.87；与全章句长仅 r=0.21
    # （不是短句化代理，独立轴）；与现口径 r=0.02；24 本真人书最低 9.82
    # > AI 185 块逐块 P90 9.47；脆弱书 0。
    qsents = []
    for p in ps:
        if not QUOTE.search(p):
            continue
        qs = [m.start() for m in re.finditer("[" + QALL + "]", p)]
        if len(qs) % 2:
            continue
        for i in range(0, len(qs), 2):
            for x in re.split(r"[。！？…]+", p[qs[i] + 1:qs[i + 1]]):
                x = re.sub(r"\s", "", x)
                if len(x) >= 2:
                    qsents.append(len(x))
    short = [s for s in ss if len(s) <= 10]
    k = max(len(re.sub(r"\s", "", body)), 1) / 1000.0
    # 无对话的章返回 None 而**不是 0**（2026-09-14 改）。取 0 会让叙述型章节
    # 被系统性判成「AI 对话写法」——达标线 15.48，0 分等于该项整项扣光。
    # None 表示「本章不适用」，_wavg() 跳过它并按剩余权重归一，既不奖也不罚。
    # item_score() / server.med() / audit.py 均已支持 None。
    return {
        "dial_sent": (sum(qsents) / len(qsents)) if qsents else None,
        "net_oral": len(ORAL.findall(body)) / k,
        "net_short": len(short) / max(len(ss), 1),
    }


def _ttr(body, n=2):
    """词汇多样性：不同 n-gram 数 / 汉字总数 × 100（逐章算，汇总取中位）。

    **2026-09-13 起退出打分，只算原始值备查。**
    区分度弱，不可当 AI / 真人的判据：同一实现下实测，真人长篇与 AI 文本
    的逐章中位完全重叠（真人 11.6–82.8，AI 47.1–80.3），且其中一篇 AI 的
    ttr 是全体最高。
    （旧注释里「真人 36–54、AI 22–34」的数字与当前实现不可复现，已删。）
    """
    c = re.sub(r"[^\u4e00-\u9fa5]", "", body)
    if len(c) < n + 1:
        return 0.0
    grams = set(c[i:i + n] for i in range(len(c) - n + 1))
    return len(grams) / len(c) * 100


def _short_run(ps):
    run = best = 0
    for p in ps:
        if len(re.sub(r"\s", "", p)) <= 12:
            run += 1
            best = max(best, run)
        else:
            run = 0
    return best


def rhythm_stats(body, ss, ps):
    k = max(len(re.sub(r"\s", "", body)), 1) / 1000.0
    L = sorted(len(s) for s in ss) or [0]
    PL = [len(re.sub(r"\s", "", p)) for p in ps]
    pcv = (statistics.pstdev(PL) / statistics.mean(PL)) if len(PL) > 2 else 0.0
    return {
        "sent_p90": float(L[min(int(len(L) * 0.90), len(L) - 1)]),
        "sent_p10": float(L[int(len(L) * 0.10)]),
        "para_cv": pcv,
        "lit": len(LIT.findall(body)) / k,
        # punc_den（停顿标点密度/千字）2026-09-15 起参与打分（节奏维）。
        # 与 comma_in 有意重叠：两半合成后才有效，见 RHY_GOOD_BAD 里的实测。
        "punc_den": sum(1 for c in body if c in PAUSE) / k,
        # act（动作密度）2026-09-14 起**参与打分**（代入感维）——见 IMM_GOOD_BAD
        # 里的注。此前 2026-09-13 曾以「方向为反」退出，那是把「方向错」当成了
        # 「没信号」：good() 的达标值可小于超标值，取反即可用，sep 与方向无关。
        "act": len(ACT.findall(body)) / k,
        "emo": len(EMO_ALL.findall(body)) / k,
    }


def near_dup(body, n=28):
    ps = [re.sub(r"[^\u4e00-\u9fa5]", "", p) for p in paras(body)]
    ps = [p for p in ps if len(p) >= n]
    seen, dups = set(), []
    for p in ps:
        key = p[:n]
        if key in seen:
            dups.append(p[:34])
        else:
            seen.add(key)
    return dups


def crowd_flat(body):
    run = 0
    for p in paras(body):
        if len(re.sub(r"\s", "", p)) <= 8 and NOD.search(p):
            run += 1
            if run >= 3:
                return True
        else:
            run = 0
    return False


def tail_lyric(body):
    ps = paras(body)
    return LYRIC.findall("".join(ps[-3:])) if ps else []


def compliance(body, title=""):
    """硬规则检查，分三级：

    A 级（写作硬伤，默认报）：圆括号注记污染 / 违禁元词 / 破折号超限 /
        正文加粗 / 章内近重复 / 群像禁忌 / 章末抒情偷跑
    B 级（体例，仅 --strict）：阿拉伯数字 / 拉丁字母 / 罗马数字
    C 级（实测反向，仅 --strict 参考）：文学腔（缓缓/微微/不禁…）——老书反而更多
    """
    out = []
    if compliance.strict:
        la = sorted(set(LATIN.findall(body)))
        if la:
            out.append(("[B]拉丁字母", f"{len(LATIN.findall(body))} 处 " + "".join(la)[:20]))
        ar = sorted(set(ARABIC.findall(body)))
        if ar:
            out.append(("[B]阿拉伯数字", f"{len(ARABIC.findall(body))} 处 " + "".join(ar)))
        rm = sorted(set(ROMAN.findall(body)))
        if rm:
            out.append(("[B]罗马数字", f"{len(ROMAN.findall(body))} 处"))
    pr = PAREN.findall(body)
    if pr:
        out.append(("圆括号·注记污染", f"{len(pr)} 处 例:{pr[0][:18]}"))
    bw = [w for w in BAN_WORDS if w in body]
    if BAN_CODE.search(body):
        bw.append("编号(如E12/L3/F8)")
    if bw:
        out.append(("违禁元词", "、".join(bw)))
    d = body.count("\u2014\u2014")
    if d > 3:
        out.append(("破折号超限", f"{d} 处 (>3)"))
    bd = len(BOLD.findall(body))
    if bd:
        out.append(("正文加粗", f"{bd} 处"))
    nd = near_dup(body)
    if nd:
        out.append(("章内近重复", f"{len(nd)} 处 例:{nd[0][:22]}"))
    if crowd_flat(body):
        out.append(("群像禁忌", "连续 3 段点头/沉默"))
    tl = tail_lyric(body)
    if tl:
        out.append(("章末抒情偷跑", "、".join(sorted(set(tl)))))
    if compliance.strict:
        cl = CLICHE.findall(body)
        if cl:
            out.append(("[C]文学腔(参考)", "、".join(sorted(set(cl)))))
    return out


